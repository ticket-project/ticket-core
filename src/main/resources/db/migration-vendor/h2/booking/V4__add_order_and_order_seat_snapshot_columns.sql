-- 표시값을 snapshot으로 남긴다. catalog 값이 나중에 바뀌어도 이미 만든 주문 상세가 바뀌지 않게
-- 하기 위해서다. 동시에 Payment 실패는 더 이상 Order를 끝내는 사건이 아니므로(ADR 0005 결정 5)
