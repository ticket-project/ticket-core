-- 환경(BookingModuleSlicingSchemaTest/OracleMigrationCompatibilityTest의 최소 baseline 등)에서는
-- no-op이어야 한다. ORDER_SEATS는 그 baseline에도 order_id 컬럼 하나짜리로 존재하므로(__root V4가
-- 참조), unique 제약/색인은 performance_seat_id 컬럼이 실제로 있을 때만 추가한다.

